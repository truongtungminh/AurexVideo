  function translate(value) {
    const trimmed = String(value || '').trim();
    if (!trimmed) return value;
    let translated = dictionary.get(trimmed);
    if (!translated) {
      for (const [pattern, replacement] of patterns) {
        if (pattern.test(trimmed)) {
          translated = trimmed.replace(pattern, replacement);
          break;
        }
      }
    }
    if (!translated) return value;
    const leading = value.match(/^\s*/)?.[0] || '';
    const trailing = value.match(/\s*$/)?.[0] || '';
    return `${leading}${translated}${trailing}`;
  }

  function translateElement(root) {
    if (language !== 'en') return;
    const nodes = [];
    if (root.nodeType === Node.TEXT_NODE) nodes.push(root);
    else if (root.nodeType === Node.ELEMENT_NODE || root.nodeType === Node.DOCUMENT_FRAGMENT_NODE) {
      const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
      while (walker.nextNode()) nodes.push(walker.currentNode);
    }
    nodes.forEach((node) => {
      if (node.parentElement?.closest('script, style, textarea, [data-no-i18n]')) return;
      const next = translate(node.nodeValue);
      if (next !== node.nodeValue) node.nodeValue = next;
    });
    const elements = root.nodeType === Node.ELEMENT_NODE ? [root, ...root.querySelectorAll('*')] : [...(root.querySelectorAll?.('*') || [])];
    elements.forEach((element) => {
      ['aria-label', 'title', 'placeholder', 'data-upgrade-label', 'data-copy-label'].forEach((attribute) => {
        if (!element.hasAttribute(attribute)) return;
        const value = element.getAttribute(attribute);
        const next = translate(value);
        if (next !== value) element.setAttribute(attribute, next);
      });
    });
  }

  function initialize() {
    if (!document.body) {
      document.addEventListener('DOMContentLoaded', initialize, { once: true });
      return;
    }
    translateElement(document.body);
    if (language === 'en') {
      new MutationObserver((mutations) => mutations.forEach((mutation) => mutation.addedNodes.forEach(translateElement)))
        .observe(document.body, { childList: true, subtree: true });
    }
  }

  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', initialize, { once: true });
  else initialize();
